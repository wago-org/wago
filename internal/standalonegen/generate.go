// Package standalonegen emits build-specific Go initializers for standalone
// executables. It has no native-module file format or runtime decoder.
package standalonegen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

// Dispatcher is installed only by the standalone build-helper profile.
var Dispatcher func() (any, error)

const implementation = "github.com/wago-org/wago/src/wago"

type generator struct {
	imports map[string]string
	active  map[uintptr]bool
}

// Generate captures a freshly compiled module as a Go factory inside the
// implementation package. Compilation and this generator never enter the final
// executable. Mutable caches, process addresses and synchronization state are
// deliberately excluded; unexpected nonzero process state fails the build.
func Generate(compiled any, factory string) ([]byte, error) {
	if !token.IsIdentifier(factory) || factory == "_" {
		return nil, fmt.Errorf("invalid standalone factory name %q", factory)
	}
	v := reflect.ValueOf(compiled)
	if v.Kind() != reflect.Pointer || v.IsNil() || v.Elem().Type().PkgPath() != implementation || v.Elem().Type().Name() != "Compiled" {
		return nil, fmt.Errorf("standalone generator requires a compiled module")
	}
	memo := v.Elem().FieldByName("validateMemo")
	if !memo.IsNil() {
		if !memo.Elem().FieldByName("err").IsNil() {
			return nil, fmt.Errorf("compiled module has failed validation")
		}
		execution := memo.Elem().FieldByName("execution")
		if !execution.IsNil() {
			v = execution
		}
	}
	g := generator{imports: map[string]string{}, active: map[uintptr]bool{}}
	literal, err := g.value(v)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by wago compile; DO NOT EDIT.\npackage wago\n\n")
	if len(g.imports) != 0 {
		out.WriteString("import (\n")
		paths := make([]string, 0, len(g.imports))
		for p := range g.imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		for _, p := range paths {
			fmt.Fprintf(&out, "%s %q\n", g.imports[p], p)
		}
		out.WriteString(")\n")
	}
	fmt.Fprintf(&out, "func %s() *Compiled {\nc := %s\n", factory, literal)
	out.WriteString("for i := range c.GCTypeDescs { c.GCTypeDescs[i].PrepareScanPlan() }\nreturn installCompilerCompiledFinalizer(c)\n}\n")
	result, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format standalone initializer: %w", err)
	}
	return result, nil
}

func (g *generator) typ(t reflect.Type) string {
	if t.Name() != "" {
		if t.PkgPath() == "" || t.PkgPath() == implementation {
			return t.Name()
		}
		alias, ok := g.imports[t.PkgPath()]
		if !ok {
			alias = fmt.Sprintf("imagepkg%d", len(g.imports))
			g.imports[t.PkgPath()] = alias
		}
		return alias + "." + t.Name()
	}
	switch t.Kind() {
	case reflect.Pointer:
		return "*" + g.typ(t.Elem())
	case reflect.Slice:
		return "[]" + g.typ(t.Elem())
	case reflect.Array:
		return fmt.Sprintf("[%d]%s", t.Len(), g.typ(t.Elem()))
	case reflect.Map:
		return "map[" + g.typ(t.Key()) + "]" + g.typ(t.Elem())
	}
	return t.String()
}

func omit(t reflect.Type, field string) bool {
	if t.PkgPath() == implementation {
		switch t.Name() {
		case "Compiled":
			return field == "customInstructions" || field == "gcCodeTelemetry" || field == "hasGCCodeTelemetry"
		case "compiledCodeCache":
			return field == "profileCacheState" || field == "mu" || field == "mem" || field == "base" || field == "refs" || field == "closed" || field == "sealed"
		case "validateMemo":
			return field == "execution" || field == "once" || field == "err" || field == "hostThunks" || field == "structuralCallIdentities"
		case "compiledCacheIndexes":
			return field == "valueTypeIndex" || field == "gcTypeMapping" || field == "funcrefImportState" || field == "failedMappings" || field == "unmapCode" || field == "mapThunkCode" || field == "sealCode"
		case "rv64ExecutionContract":
			return field == "verified" || field == "rooted"
		}
	}
	// These two derived scan links are rebuilt by PrepareScanPlan, in their
	// owning package, instead of reaching into foreign private fields.
	return t.PkgPath() == "github.com/wago-org/wago/src/core/runtime/gc/native" && (field == "firstRef" || field == "nextRef")
}

func (g *generator) value(v reflect.Value) (string, error) {
	t := v.Type()
	switch v.Kind() {
	case reflect.Bool:
		return strconv.FormatBool(v.Bool()), nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return g.typ(t) + "(" + strconv.FormatInt(v.Int(), 10) + ")", nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return g.typ(t) + "(" + strconv.FormatUint(v.Uint(), 10) + ")", nil
	case reflect.String:
		return strconv.Quote(v.String()), nil
	case reflect.Pointer:
		if v.IsNil() {
			return "nil", nil
		}
		pointer := v.Pointer()
		if g.active[pointer] {
			return "", fmt.Errorf("cyclic standalone metadata: %s", t)
		}
		g.active[pointer] = true
		s, e := g.value(v.Elem())
		delete(g.active, pointer)
		return "&" + s, e
	case reflect.Struct:
		var b strings.Builder
		b.WriteString(g.typ(t) + "{")
		for i := 0; i < v.NumField(); i++ {
			f := t.Field(i)
			child := v.Field(i)
			if omit(t, f.Name) || child.IsZero() {
				continue
			}
			if f.PkgPath != "" && t.PkgPath() != implementation {
				return "", fmt.Errorf("unsupported private standalone metadata: %s.%s", t, f.Name)
			}
			s, e := g.value(child)
			if e != nil {
				return "", fmt.Errorf("%s.%s: %w", t, f.Name, e)
			}
			fmt.Fprintf(&b, "%s:%s,", f.Name, s)
		}
		b.WriteString("}")
		return b.String(), nil
	case reflect.Slice, reflect.Array:
		if v.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 && t.Elem().PkgPath() == "" && !v.IsNil() {
			return g.typ(t) + "(" + strconv.Quote(string(v.Bytes())) + ")", nil
		}
		if v.Kind() == reflect.Slice && v.IsNil() {
			return "nil", nil
		}
		var b strings.Builder
		b.WriteString(g.typ(t) + "{")
		for i := 0; i < v.Len(); i++ {
			s, e := g.value(v.Index(i))
			if e != nil {
				return "", e
			}
			b.WriteString(s + ",")
		}
		b.WriteString("}")
		return b.String(), nil
	case reflect.Map:
		if v.IsNil() {
			return "nil", nil
		}
		type entry struct{ k, v string }
		entries := make([]entry, 0, v.Len())
		iter := v.MapRange()
		for iter.Next() {
			k, e := g.value(iter.Key())
			if e != nil {
				return "", e
			}
			s, e := g.value(iter.Value())
			if e != nil {
				return "", e
			}
			entries = append(entries, entry{k, s})
		}
		sort.Slice(entries, func(i, j int) bool { return entries[i].k < entries[j].k })
		var b strings.Builder
		b.WriteString(g.typ(t) + "{")
		for _, entry := range entries {
			b.WriteString(entry.k + ":" + entry.v + ",")
		}
		b.WriteString("}")
		return b.String(), nil
	default:
		return "", fmt.Errorf("unsupported process-local standalone metadata: %s", t)
	}
}
