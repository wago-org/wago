// StandaloneRuntimeProfile emits link-time selections for the single-module
// launcher without plugins, including whether it needs a reference store or a
// collector. It reads the same execution snapshot as the image generator.
func (c *Compiled) StandaloneRuntimeProfile() (source []byte, referenceStore, collector bool) {
	c = c.executionView()
	functionImports := c.NumImports != 0
	funcrefStorage := c.hasFuncrefImportContainers()
	foreignHostControl := functionImports || funcrefStorage
	hasData := c.activeDataCount() != 0
	hasImports := c.declaredImportCount() != 0
	features := compiledStructuralRequiredFeatures(c)
	table64 := features.IsEnabled(CoreFeatureTable64)
	rv64 := compiledArchitecture == 4
	tableCount := c.tableCount()
	tableABI := c.nativeTable64ABI
	// Indexed Table32 witnesses cover only two owned Table32 declarations.
	indexedTable32 := rv64 && tableCount == 2 && c.tableImportCount() == 0 &&
		!c.TableAddr64 && !c.tableDef(1).Addr64
	// A generic RV64 table has a complete source execution contract. The
	// operation-specific and state-only proofs serve older retained images.
	legacyTable64 := rv64 && table64 &&
		(tableABI != nativeTable64NoABI || !rv64SourceContractValid(c))
	// Run full admission before dropping the legacy fingerprints. The execution
	// contract lets the launcher verify that it received the same code and globals.
	mutableFuncrefGlobals := rv64 && (c.hasMutableFuncrefGlobals() || !rv64SourceContractValid(c) || railshotValidateCompiled(c) != nil)
	compactExternConstruction := compactExternConstructionNeeded(c)
	collector = compactExternConstruction || c.standaloneNeedsNativeCollector(features)
	referenceStore = c.standaloneNeedsReferenceStore(features, collector, foreignHostControl)
	syncHostControl := c.importsRequireSyncWithAtomicHelpers(nil, false, c.codeCache.atomicHelpers != 0)
	storage := c.standaloneInstanceStorage(collector, syncHostControl)
	elements := c.standaloneElementPayloads()
	initializers := elements.initializers
	globalOffsets, offsetExpressions := c.standaloneSegmentOffsets(&initializers)
	for _, global := range c.Globals {
		initializers.record(global.InitExpr)
	}
	tail := railshotStandaloneNativeTail(c)
	calls := c.standaloneCallProfile()
	structHelpers, arrayHelpers := c.standaloneGCHelperFamilies()
	managedAggregateHelpers := managedAggregateHelperFamilies(c)
	compactExternDispatch := c.compactExternFrameRoots()
	compactExternTables := compactExternDispatch && c.standaloneHasExternTables()
	compactExternStorageImports := compactExternDispatch && (c.tableImportCount() != 0 || len(c.GlobalImports) != 0)
	compactExternElements := compactExternDispatch && slices.ContainsFunc(c.passiveElems, func(elem ElemInit) bool {
		return normalizedElemRefType(elem.RefType) == ValExternRef
	})
	selections := []struct {
		name    string
		enabled bool
	}{
		{"FunctionCode", storage.functionCode},
		{"RetainedNativeContext", storage.nativeContext},
		{"JobMemory", storage.jobMemory},
		{"FunctionImports", functionImports},
		{"ForeignHostControl", foreignHostControl},
		{"NativeStackHostControl", railshotRequiresNativeHostControl(c)},
		{"GuestGlobalStore", c.usesGuestGlobalStoreHelper()},
		{"RV64NativeTailMetadata", rv64 && c.requiredFeatures.IsEnabled(CoreFeatureTailCall)},
		{"DirectNativeTailPlans", tail.directImports},
		{"IndirectNativeTailPlans", tail.indirect},
		{"ReferenceNativeTailPlans", tail.reference},
		{"LegacyNativeTailReferenceCarriers", tail.legacyReferenceCarriers},
		{"NameSection", c.Names != nil},
		{"SyncHostControl", syncHostControl},
		{"RV64NativeOwnerScope", rv64 && (functionImports || railshotRequiresNativeOwnerScope(c))},
		{"RV64CallableTableRows", rv64 && (foreignHostControl || c.hasFuncrefTable())},
		{"FunctionReexports", c.standaloneHasFunctionReexports()},
		{"LocalStart", c.HasStart && !c.StartIsImport},
		{"ImportedStart", c.HasStart && c.StartIsImport},
		{"GuardedGrowth", slices.ContainsFunc(c.InternalEntry, guardedMemoryGrowEntry)},
		{"GuardedMemory", c.HasMemory && (c.boundsMode == BoundsChecksSignalsBased || c.prefersGuardMemory())},
		{"SharedMemory", c.standaloneHasSharedMemory()},
		{"ModuleImports", hasImports},
		{"Memories", c.memoryCount() != 0},
		{"MemoryImports", c.memoryImportCount() != 0},
		{"ExceptionHandling", c.requiredFeatures.IsEnabled(CoreFeatureExceptionHandling)},
		{"ExceptionTags", c.memoryDir != nil && len(c.memoryDir.exceptionTags()) != 0},
		{"OwnedExceptionReferences", c.needsOwnedExceptionReferences()},
		{"TagImports", c.tagImportCount() != 0},
		{"FuncrefStorageImports", funcrefStorage},
		{"AtomicNotify", c.codeCache.usesAtomicHelper(shared.AtomicHelperNotify)},
		{"AtomicWait32", c.codeCache.usesAtomicHelper(shared.AtomicHelperWait32)},
		{"AtomicWait64", c.codeCache.usesAtomicHelper(shared.AtomicHelperWait64)},
		{"AtomicIndexedMemory", c.codeCache.atomicHelpers&shared.AtomicHelperUsesIndexedMemory != 0},
		{"AtomicMemory64", c.codeCache.atomicHelpers&shared.AtomicHelperUsesMemory64 != 0},
		{"AtomicNotifyPending", c.requiresNotifyPending},
		{"SharedGrowthHelpers", c.codeCache.usesAtomicHelper(shared.AtomicHelperMemoryGrow)},
		{"NativeCollector", collector},
		{"DetailedGCTypeDescs", slices.ContainsFunc(c.GCTypeDescs, gcTypeDescNeedsDetails)},
		{"I31Execution", c.stagedGCI31Product() != 0},
		{"GCStructHelpers", structHelpers},
		{"GCArrayHelpers", arrayHelpers},
		{"StagedGCExternConversion", c.stagedGCStructProduct().requiresExternConversion()},
		{"CompactExternDispatch", compactExternDispatch},
		{"CompactExternTables", compactExternTables},
		{"CompactExternElements", compactExternElements},
		{"CompactExternConstruction", compactExternConstruction},
		{"ManagedFunctionConstruction", managedAggregateHelpers != 0},
		{"ManagedFunctionGraph", compiledManagedFunctionReachability(c) || managedAggregateHelpers != 0 || compactExternStorageImports},
		{"RootedReceipts", rv64RootedReceiptsBuilt && c.nativeGCABIRequirement() == gc.NativeABIVersion},
		{"RV64LegacyGCProducts", railshotNeedsLegacyGCProducts(c)},
		{"ReferenceStore", referenceStore},
		{"StructuralCallKeys", c.needsFuncRefDescs()},
		{"FuncRefContextHeader", c.needsFuncRefContextHeader},
		{"TypedCallKeys", rv64 && compiledUsesTypedSignatures(c)},
		{"AggregateTypes", hasAggregateTypeDeclarations(c.Types)},
		{"ReferenceTypeDescriptors", c.standaloneHasReferenceTypeDescriptors()},
		{"TypeLinks", slices.ContainsFunc(c.Types, DefinedTypeDescriptor.hasTypeLinks)},
		{"DirectPairResults", calls.intPair},
		{"DirectIntFixed", calls.intBoundedFull || calls.intBoundedLight || calls.intUnboundedFull || calls.intUnboundedLight},
		{"DirectIntBoundedFull", calls.intBoundedFull},
		{"DirectIntBoundedLight", calls.intBoundedLight},
		{"DirectIntUnboundedFull", calls.intUnboundedFull},
		{"DirectIntUnboundedLight", calls.intUnboundedLight},
		{"PreparedZeroArgNarrowResult", calls.preparedZeroArgNarrowResult},
		{"PreparedZeroArgWideResult", calls.preparedZeroArgWideResult},
		{"PreparedIntOneArg", calls.preparedIntOneArg},
		{"CachedIntOneArg", calls.cachedIntOneArg},
		{"CachedBoundedI32OneArg", calls.cachedBoundedI32OneArg},
		{"PreparedUnboundedLightI32OneArg", calls.preparedUnboundedLightI32OneArg},
		{"DirectIntWide", calls.intWide},
		{"DirectIntOct", calls.intOct},
		{"DirectFloatFour", calls.floatFour},
		{"DirectFloatOct", calls.floatOct},
		{"DirectMixed", calls.mixed},
		{"MultiMemory", c.memoryCount() > 1},
		{"ActiveData", hasData},
		{"Core1DataPreflight", c.core1SegmentPreflight && hasData},
		{"Core1ElementPreflight", c.core1SegmentPreflight && len(c.Elems) != 0},
		{"Tables", c.HasTable},
		{"MultiTable", tableCount > 1},
		{"LegacyTable32Instructions", indexedTable32 && tableABI >= nativeTable64SizeABI && tableABI <= nativeTable64InitDropABI},
		{"StateOnlyTable32", indexedTable32 && tableABI == nativeTable64NoABI && c.hasNoFunctionCode()},
		{"Table64", table64},
		{"LegacyTable64", legacyTable64},
		{"TableImports", c.tableImportCount() != 0},
		{"TableInitializers", c.hasTableFunctionInitializers()},
		{"Globals", len(c.Globals) != 0},
		{"RV64MutableFuncrefGlobals", mutableFuncrefGlobals},
		{"RV64ReferenceFunctions", rv64 && c.nativeReferenceFunctionABI},
		{"RV64TableCapacities", rv64 && len(c.rv64ExecutionTableCapacities()) != 0},
		{"RV64ReferenceCalls", rv64 && (c.nativeReferenceCallABI || c.nativeReferenceControlABI)},
		{"GlobalImports", len(c.GlobalImports) != 0},
		{"ActiveElements", len(c.Elems) != 0},
		{"PassiveElements", len(c.passiveElems) != 0},
		{"ElementGlobals", elements.globals},
		{"ElementExpressions", elements.expressions},
		{"ElementRepeats", elements.repeats},
		{"PassiveData", len(c.PassiveData) != 0},
		{"GlobalInitExpressions", slices.ContainsFunc(c.Globals, func(global GlobalDef) bool { return len(global.InitExpr) != 0 })},
		{"SegmentGlobalOffsets", globalOffsets},
		{"SegmentOffsetExpressions", offsetExpressions},
	}
	source = []byte("// Code generated by Wago. DO NOT EDIT.\n\npackage buildfeatures\n\nconst (\n")
	for _, selection := range selections {
		source = fmt.Appendf(source, "\tStandalone%s = %t\n", selection.name, selection.enabled)
	}
	source = fmt.Appendf(source, "\tStandaloneElementTypes = %#x\n\tStandaloneGCConstOpcodes = %#x\n", elements.types, initializers.gc)
	gcHelpers := c.codeCache.standaloneGCHelperMask()
	source = fmt.Appendf(source, "\tStandaloneGCHelperMask = %#x\n", gcHelpers)
	source = fmt.Appendf(source, "\tStandaloneRV64LegacyI31ProductMask = %#x\n", railshotLegacyI31ProductMask(c))
	source = fmt.Appendf(source, "\tStandaloneManagedAggregateHelpers = %#x\n", gcHelpers&managedAggregateHelpers)
	source = fmt.Appendf(source, "\tStandaloneInvocationTypes = %#x\n", c.invocationTypes())
	source = fmt.Appendf(source, "\tStandaloneMaxFixedDirectArgs = %d\n", calls.maxFixedArgs)
	source = fmt.Appendf(source, "\tStandaloneFixedIntArgCount = %d\n\tStandaloneBoundedLightIntArgCount = %d\n",
		calls.fixedIntArgCount(), calls.intBoundedLightArgs)
	source = fmt.Appendf(source, "\tStandaloneFixedIntI32Args = %#x\n\tStandaloneFixedIntI64Args = %#x\n\tStandaloneFixedIntResults = %#x\n",
		calls.fixedIntI32Args, calls.fixedIntI64Args, calls.fixedIntResults)
	source = calls.pairIntWidths.appendProfile(source, "PairInt")
	source = calls.wideIntWidths.union(calls.octIntWidths).appendProfile(source, "WideInt")
	source = calls.floatFourWidths.appendProfile(source, "FloatFour")
	source = calls.floatOctWidths.appendProfile(source, "FloatOct")
	source = calls.mixedWidths.appendProfile(source, "Mixed")
	source = fmt.Appendf(source, "\tStandaloneMixedResultForms = %#x\n", calls.mixedResultForms)
	source = fmt.Appendf(source, "\tStandaloneMixedGPArgs = %#x\n\tStandaloneMixedFPArgs = %#x\n\tStandaloneMixedGPResults = %#x\n\tStandaloneMixedFPResults = %#x\n",
		calls.mixedGPArgs, calls.mixedFPArgs, calls.mixedGPResults, calls.mixedFPResults)
	source = fmt.Appendf(source, "\tStandaloneConstExprLowOpcodes = %#x\n\tStandaloneConstExprNumericOpcodes = %#x\n\tStandaloneConstExprReferenceOpcodes = %#x\n",
		initializers.opcodes[0], initializers.opcodes[1], initializers.opcodes[3])
	// Bare launchers have no storage bindings. Use the ordinary preflight
	// to select the missing import in its normal priority order.
	var storageDiagnostic string
	if err := c.preflightImportBindings(nil); err != nil {
		storageDiagnostic = err.Error()
	}
	source = fmt.Appendf(source, "\tStandaloneUnboundStorageDiagnostic = %q\n", storageDiagnostic)
	// Carry static failures to their ordinary validation stages, around the
	// destination's native admission and collector ABI checks.
	var structuralDiagnostic string
	if err := c.validateStructuralMetadata(); err != nil {
		structuralDiagnostic = err.Error()
	}
	source = fmt.Appendf(source, "\tStandaloneStructuralDiagnostic = %q\n", structuralDiagnostic)
	// These sizes use the target's native ABI constants. Keep the serialized
	// image intact until startup has checked its native execution contract.
	layout := *c
	var arenaDiagnostic string
	if structuralDiagnostic == "" {
		if err := layout.validateArenaFootprintForImage(storage.functionCode, storage.nativeContext); err != nil {
			arenaDiagnostic = err.Error()
		}
	}
	source = fmt.Appendf(source, "\tStandaloneArenaDiagnostic = %q\n\tStandaloneArenaBytes = %d\n\tStandaloneMaxParamSlots = %d\n\tStandaloneMaxResultSlots = %d\n\tStandaloneSyncHostSlots = %d\n",
		arenaDiagnostic, layout.instantiateArenaNeed, layout.maxParamSlots, layout.maxResultSlots, layout.syncHostSlots)
	return append(source, ")\n"...), referenceStore, collector
}

type standaloneInstanceStorage struct {
	functionCode  bool
	nativeContext bool
	jobMemory     bool
}

func (c *Compiled) standaloneInstanceStorage(collector, syncHostControl bool) standaloneInstanceStorage {
	functionCode := !c.hasNoFunctionCode()
	// Storage and collector metadata can use the native directory even
	// when the image has no callable entries.
	nativeContext := functionCode || c.HasTable || c.memoryImportCount() != 0 ||
		buildfeatures.NativeCollectorFrameRoots && collector
	// Basedata holds native entry control and pointers to instance-owned state.
	jobMemory := nativeContext || c.memoryCount() != 0 || len(c.Globals) != 0 ||
		len(c.PassiveData) != 0 || len(c.passiveElems) != 0 ||
		c.memoryDir != nil && len(c.memoryDir.exceptionTags()) != 0 ||
		c.needsFuncRefDescs() || c.needsFuncRefContextHeader || syncHostControl
	return standaloneInstanceStorage{
		functionCode: functionCode, nativeContext: nativeContext, jobMemory: jobMemory,
	}
}

func (c *Compiled) standaloneHasExternTables() bool {
	for i := 0; i < c.tableCount(); i++ {
		if c.tableElementType(i) == ValExternRef {
			return true
		}
	}
	return false
}

func (c *Compiled) standaloneHasSharedMemory() bool {
	for index := 0; index < c.memoryCount(); index++ {
		if c.memoryDef(index).Shared {
			return true
		}
	}
	return false
}

func (c *Compiled) standaloneHasFunctionReexports() bool {
	for _, index := range c.Exports {
		if index < c.NumImports {
			return true
		}
	}
	return false
}

func (c *Compiled) standaloneSegmentOffsets(initializers *standaloneConstExprProfile) (globals, expressions bool) {
	for _, elem := range c.Elems {
		globals = globals || elem.Offset.HasGlobal
		expressions = expressions || len(elem.Offset.Expr) != 0
		initializers.record(elem.Offset.Expr)
	}
	for _, elem := range c.passiveElems {
		// Retained element state can carry offsets in serialized metadata.
		globals = globals || elem.Offset.HasGlobal
		expressions = expressions || len(elem.Offset.Expr) != 0
		initializers.record(elem.Offset.Expr)
	}
	for index := 0; index < c.activeDataCount(); index++ {
		data, _ := c.activeDataInfoAt(index)
		globals = globals || data.Offset.HasGlobal
		expressions = expressions || len(data.Offset.Expr) != 0
		initializers.record(data.Offset.Expr)
	}
	return globals, expressions
}

type standaloneElementProfile struct {
	globals      bool
	expressions  bool
	repeats      bool
	types        uint16
	initializers standaloneConstExprProfile
}

func (c *Compiled) standaloneElementPayloads() standaloneElementProfile {
	var profile standaloneElementProfile
	for _, segments := range [][]ElemInit{c.Elems, c.passiveElems} {
		for _, segment := range segments {
			if len(segment.Values) != 0 {
				profile.types |= 1 << normalizedElemRefType(segment.RefType)
			}
			for _, value := range segment.Values {
				profile.globals = profile.globals || value.HasGlobal
				if len(value.Expr) != 0 {
					profile.expressions = true
					profile.initializers.record(value.Expr)
				}
				profile.repeats = profile.repeats || value.RepeatPrevious
			}
		}
	}
	return profile
}

// The top-level mask is indexed by opcode byte. GC instructions share
// the 0xfb prefix and select their handlers by subopcode.
type standaloneConstExprProfile struct {
	opcodes [4]uint64
	gc      uint32
}

func (profile *standaloneConstExprProfile) record(expr []byte) {
	r := wasm.ReaderFrom(expr)
	for r.HasNext() {
		op, err := r.Byte()
		if err != nil {
			profile.enableAll()
			return
		}
		sub, _, err := readConstImmediate(&r, op)
		if err != nil {
			profile.enableAll()
			return
		}
		profile.opcodes[op/64] |= 1 << (op % 64)
		if op == 0xfb {
			profile.gc |= 1 << sub
		}
	}
}

func (profile *standaloneConstExprProfile) enableAll() {
	for i := range profile.opcodes {
		profile.opcodes[i] = ^uint64(0)
	}
	profile.gc = ^uint32(0)
}

type standaloneCallProfile struct {
	intBoundedFull, intBoundedLight                          bool
	intBoundedLightArgs                                      int
	intUnboundedFull, intUnboundedLight                      bool
	intPair, intWide, intOct                                 bool
	floatFour, floatOct, mixed                               bool
	preparedZeroArgNarrowResult, preparedZeroArgWideResult   bool
	preparedIntOneArg, cachedIntOneArg                       bool
	cachedBoundedI32OneArg                                   bool
	preparedUnboundedLightI32OneArg                          bool
	fixedIntI32Args, fixedIntI64Args, fixedIntResults        uint8
	pairIntWidths, wideIntWidths, octIntWidths               standaloneBankWidths
	floatFourWidths, floatOctWidths, mixedWidths             standaloneBankWidths
	mixedResultForms                                         uint8
	mixedGPArgs, mixedFPArgs, mixedGPResults, mixedFPResults uint8
	mixedMaxGPArgs, mixedMaxFPArgs                           int
	mixedMaxGPResults, mixedMaxFPResults                     int
	maxFixedArgs                                             int
}

type standaloneBankWidths struct {
	narrowArgs, wideArgs, narrowResults, wideResults uint8
}

func (profile standaloneCallProfile) fixedIntArgCount() int {
	return bits.Len8(profile.fixedIntI32Args | profile.fixedIntI64Args)
}

func (widths standaloneBankWidths) maxArgs() int {
	return bits.Len8(widths.narrowArgs | widths.wideArgs)
}

func (widths standaloneBankWidths) maxResults() int {
	return bits.Len8(widths.narrowResults | widths.wideResults)
}

func (widths standaloneBankWidths) union(other standaloneBankWidths) standaloneBankWidths {
	return standaloneBankWidths{
		narrowArgs:    widths.narrowArgs | other.narrowArgs,
		wideArgs:      widths.wideArgs | other.wideArgs,
		narrowResults: widths.narrowResults | other.narrowResults,
		wideResults:   widths.wideResults | other.wideResults,
	}
}

func bankWidthMasks(types []ValType) (narrow, wide uint8) {
	for slot, typ := range types {
		if !isWideValType(typ) {
			narrow |= 1 << slot
		} else {
			wide |= 1 << slot
		}
	}
	return narrow, wide
}

func (widths *standaloneBankWidths) record(sig FuncSig) {
	narrowArgs, wideArgs := bankWidthMasks(sig.Params)
	narrowResults, wideResults := bankWidthMasks(sig.Results)
	widths.narrowArgs |= narrowArgs
	widths.wideArgs |= wideArgs
	widths.narrowResults |= narrowResults
	widths.wideResults |= wideResults
}

func (widths standaloneBankWidths) appendProfile(source []byte, bank string) []byte {
	return fmt.Appendf(source, "\tStandalone%sNarrowArgs = %#x\n\tStandalone%sWideArgs = %#x\n\tStandalone%sNarrowResults = %#x\n\tStandalone%sWideResults = %#x\n",
		bank, widths.narrowArgs, bank, widths.wideArgs, bank, widths.narrowResults, bank, widths.wideResults)
}

func (c *Compiled) standaloneCallProfile() standaloneCallProfile {
	var profile standaloneCallProfile
	// The host resolves these adapters through Invoke and WasmFunc, both of
	// which look up an export. Guest calls use their own native ABI.
	for _, export := range c.Exports {
		index := export - c.NumImports
		if index < 0 || index >= len(c.Funcs) {
			continue
		}
		sig := c.Funcs[index]
		if len(sig.Params) == 0 && len(sig.Results) == 1 {
			switch sig.Results[0] {
			case ValI32, ValF32:
				profile.preparedZeroArgNarrowResult = true
			case ValI64, ValF64:
				profile.preparedZeroArgWideResult = true
			}
		}
		if !c.directPreparedAt(index) {
			continue
		}
		integer := preparedDirectIntSupported && preparedDirectIntSignature(sig)
		bounded := c.directPreparedBoundedAt(index)
		if integer && len(sig.Params) <= 4 && len(sig.Results) <= 1 {
			profile.addFixedInteger(sig, bounded, c.directPreparedLightAt(index))
			continue
		}
		if !bounded {
			continue
		}
		switch {
		case integer:
			switch {
			case len(sig.Results) > 5:
				profile.intOct = preparedDirectWideSupported
				profile.octIntWidths.record(sig)
			case len(sig.Params) > 4 || len(sig.Results) > 2:
				profile.intWide = preparedDirectWideSupported
				profile.wideIntWidths.record(sig)
			case preparedDirectPairSupported && len(sig.Results) == 2:
				profile.intPair = true
				profile.pairIntWidths.record(sig)
				profile.maxFixedArgs = max(profile.maxFixedArgs, len(sig.Params))
				profile.preparedIntOneArg = profile.preparedIntOneArg || len(sig.Params) == 1
			}
		case preparedDirectFloatSupported && preparedDirectFloatSignature(sig):
			if len(sig.Params) > 4 || len(sig.Results) > 4 {
				profile.floatOct = true
				profile.floatOctWidths.record(sig)
			} else {
				profile.floatFour = true
				profile.floatFourWidths.record(sig)
			}
		case preparedDirectFloatSupported && preparedDirectMixedSignature(sig):
			profile.mixed = true
			profile.mixedWidths.record(sig)
			profile.mixedResultForms |= 1 << min(len(sig.Results), 2)
			fpArgs, fpResults := directMixedFloatMask(sig.Params), directMixedFloatMask(sig.Results)
			fpArgsCount, fpResultsCount := bits.OnesCount8(fpArgs), bits.OnesCount8(fpResults)
			profile.mixedMaxGPArgs = max(profile.mixedMaxGPArgs, len(sig.Params)-fpArgsCount)
			profile.mixedMaxFPArgs = max(profile.mixedMaxFPArgs, fpArgsCount)
			profile.mixedMaxGPResults = max(profile.mixedMaxGPResults, len(sig.Results)-fpResultsCount)
			profile.mixedMaxFPResults = max(profile.mixedMaxFPResults, fpResultsCount)
			profile.mixedFPArgs |= fpArgs
			profile.mixedGPArgs |= uint8(1<<len(sig.Params)-1) &^ fpArgs
			profile.mixedFPResults |= fpResults
			profile.mixedGPResults |= uint8(1<<len(sig.Results)-1) &^ fpResults
		}
	}
	return profile
}

func (profile *standaloneCallProfile) addFixedInteger(sig FuncSig, bounded, light bool) {
	switch {
	case bounded && light:
		profile.intBoundedLight = true
		profile.intBoundedLightArgs = max(profile.intBoundedLightArgs, len(sig.Params))
	case bounded:
		profile.intBoundedFull = true
	case light:
		profile.intUnboundedLight = true
	default:
		profile.intUnboundedFull = true
	}
	profile.maxFixedArgs = max(profile.maxFixedArgs, len(sig.Params))
	i32Args, i64Args := bankWidthMasks(sig.Params)
	profile.fixedIntI32Args |= i32Args
	profile.fixedIntI64Args |= i64Args
	switch {
	case len(sig.Results) == 0:
		profile.fixedIntResults |= fixedIntVoidResult
	case sig.Results[0] == ValI32:
		profile.fixedIntResults |= fixedIntI32Result
	default:
		profile.fixedIntResults |= fixedIntI64Result
	}
	if len(sig.Params) != 1 {
		return
	}
	profile.preparedIntOneArg = true
	i32ToI32 := sig.Params[0] == ValI32 && len(sig.Results) == 1 && sig.Results[0] == ValI32
	if bounded && i32ToI32 {
		profile.cachedBoundedI32OneArg = true
		return
	}
	// The bounded i32 shortcut wins before the general one-argument shortcut.
	profile.cachedIntOneArg = true
	profile.preparedUnboundedLightI32OneArg = profile.preparedUnboundedLightI32OneArg ||
		!bounded && light && i32ToI32
}

func (c *Compiled) standaloneNeedsNativeCollector(features CoreFeatures) bool {
	// Owned exception references are part of the native GC ABI. Scalar
	// exception tags and landing pads use the native context alone.
	if c.needsNativeGCABI() ||
		c.needsRuntimeGCCollectorDomain() ||
		compiledManagedFunctionReachability(c) {
		return true
	}
	// Immediate i31 values and declaration-only graphs need type metadata
	// for validation. Neither contains collector objects.
	if c.stagedGCI31Product() != 0 || c.collectorFreeTypeDeclarations() {
		return false
	}
	if !features.IsEnabled(CoreFeatureGC) && !gc.HasHeapObjectTypes(c.GCTypeDescs) {
		return false
	}
	// Authenticated primitive reference code can retain an inert aggregate
	// graph. Its only allowed GC portal here is a callable descriptor test.
	heapHelpers := c.codeCache.gcHelpers &^ (1 << gcFuncRefTest)
	return heapHelpers != shared.GCHelperUsesKnown || !railshotPrimitiveReferenceContract(c)
}

func (c *Compiled) standaloneNeedsReferenceStore(features CoreFeatures, collector, foreignHostControl bool) bool {
	// The native context header also serves numeric helpers. Callable
	// descriptors and their control bridges have separate ownership needs.
	if collector || foreignHostControl || c.usesGuestGlobalStoreHelper() || c.needsFuncRefDescs() ||
		c.nativeReferenceFunctionABI || c.nativeReferenceCallABI || c.nativeReferenceControlABI {
		return true
	}
	if c.collectorFreeTypeDeclarations() {
		return false
	}
	if c.stagedGCI31Product() != 0 {
		// Owned i31 storage holds immediate values. Imported reference cells
		// can still participate in ownership checks across instances.
		return c.tableImportCount() != 0 || slices.ContainsFunc(c.GlobalImports, func(imp GlobalImportDef) bool {
			return isReferenceValType(imp.Type)
		})
	}
	return features&(CoreFeatureReferenceTypes|CoreFeatureTypedFunctionReferences) != 0 || c.HasTable
}
