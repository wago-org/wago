// StandaloneNativeAssemblyProfile selects the native register lanes required
// by exported functions with a direct register ABI.
func (c *Compiled) StandaloneNativeAssemblyProfile() []byte {
	calls := c.executionView().standaloneCallProfile()
	if calls.fixedIntResults == 0 && !calls.intPair && !calls.intWide && !calls.intOct &&
		!calls.mixed && !calls.floatFour && !calls.floatOct {
		return nil
	}
	floatFourArgs, floatOctArgs := calls.floatFourWidths.maxArgs(), calls.floatOctWidths.maxArgs()
	wideIntArgs, octIntArgs := calls.wideIntWidths.maxArgs(), calls.octIntWidths.maxArgs()
	source := []byte("// Code generated by Wago. DO NOT EDIT.\n")
	for _, bridge := range []struct {
		name string
		args int
	}{
		{"MIXED", calls.mixedMaxGPArgs + calls.mixedMaxFPArgs},
		{"FLOAT_FOUR", floatFourArgs},
		{"FLOAT_OCT", floatOctArgs},
		{"INT_WIDE", wideIntArgs},
		{"INT_OCT", octIntArgs},
	} {
		if bridge.args != 0 {
			source = fmt.Appendf(source, "#define WAGO_%s_ARGS\n", bridge.name)
		}
	}
	if calls.fixedIntResults&(fixedIntI32Result|fixedIntI64Result) != 0 {
		source = append(source, "#define WAGO_INT_FIXED_RESULT\n"...)
	}
	for _, bank := range []struct {
		name  string
		lanes int
	}{
		{"MIXED_GP_ARG", calls.mixedMaxGPArgs},
		{"MIXED_FP_ARG", calls.mixedMaxFPArgs},
		{"MIXED_GP_RESULT", calls.mixedMaxGPResults},
		{"MIXED_FP_RESULT", calls.mixedMaxFPResults},
		{"FLOAT_FOUR_ARG", floatFourArgs},
		{"FLOAT_FOUR_RESULT", calls.floatFourWidths.maxResults()},
		{"FLOAT_OCT_ARG", floatOctArgs},
		{"FLOAT_OCT_RESULT", calls.floatOctWidths.maxResults()},
		{"INT_FIXED_ARG", calls.fixedIntArgCount()},
		{"INT_PAIR_ARG", calls.pairIntWidths.maxArgs()},
		{"INT_WIDE_ARG", wideIntArgs},
		{"INT_WIDE_RESULT", calls.wideIntWidths.maxResults()},
		{"INT_OCT_ARG", octIntArgs},
		{"INT_OCT_RESULT", calls.octIntWidths.maxResults()},
	} {
		for lane := 0; lane < bank.lanes; lane++ {
			source = fmt.Appendf(source, "#define WAGO_%s_%d\n", bank.name, lane)
		}
	}
	return source
}

type standaloneCodeProfile struct {
	gcHelpers     uint64
	atomicHelpers uint8
}

func (cc *compiledCodeCache) recordGCHelperUses(uses uint64) {
	cc.gcHelpers = uses
}

func (cc *compiledCodeCache) standaloneGCHelperMask() uint64 {
	if cc.gcHelpers == 0 {
		return ^uint64(0)
	}
	return cc.gcHelpers
}

func (c *Compiled) standaloneGCHelperFamilies() (structs, arrays bool) {
	if c.codeCache.gcHelpers == 0 {
		return c.usesGCStructHelpers(), c.usesGCArrayHelpers()
	}
	const structHelpers = (1<<gcArrayAllocDefault-1)&^
		(1|1<<gcStructTableSet|1<<gcAnyConvertExtern|1<<gcExternConvertAny|1<<gcFuncRefTest) |
		1<<gcStructReserveDeadNative | 1<<gcStructReserveDeadBatch
	const arrayHelpers = (1<<(gcArrayCheckFixed+1)-1)&^(1<<gcArrayAllocDefault-1) |
		1<<gcArrayReserveDeadBatch
	return c.codeCache.gcHelpers&structHelpers != 0, c.codeCache.gcHelpers&arrayHelpers != 0
}

func (c *Compiled) standaloneHasReferenceTypeDescriptors() bool {
	isReference := func(value ValueTypeDescriptor) bool { return value.Kind == ValueTypeReference }
	isReferenceField := func(field FieldTypeDescriptor) bool {
		return !field.Storage.Packed && isReference(field.Storage.Value)
	}
	if slices.ContainsFunc(c.ValueTypes, isReference) {
		return true
	}
	for _, typ := range c.Types {
		switch typ.Kind {
		case CompositeTypeFunction:
			if slices.ContainsFunc(typ.Params, isReference) || slices.ContainsFunc(typ.Results, isReference) {
				return true
			}
		case CompositeTypeStruct:
			if slices.ContainsFunc(typ.Fields, isReferenceField) {
				return true
			}
		case CompositeTypeArray:
			if isReferenceField(typ.Array) {
				return true
			}
		}
	}
	for _, sigs := range [][]FuncSig{c.Funcs, c.importFuncSigs} {
		for _, sig := range sigs {
			if !sig.HasTypeIndex && (hasReferenceValType(sig.Params) || hasReferenceValType(sig.Results)) {
				return true
			}
		}
	}
	return false
}

func (cc *compiledCodeCache) recordAtomicHelperUses(uses uint8) {
	cc.atomicHelpers = uses
}

func (cc *compiledCodeCache) usesAtomicHelper(helper uint32) bool {
	return cc.atomicHelpers&(1<<helper) != 0
}

