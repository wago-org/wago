func TestCodeProfileSharedLifecycleAndCodeNeutrality(t *testing.T) {
	s := NewCodeProfile(CodeProfileOptions{IncludeCode: true, SourceMaps: true, UnwindMaps: true})
	defer s.Close()
	plain, err := Compile(identityI32Module())
	if err != nil {
		t.Fatal(err)
	}
	defer plain.Close()
	c, err := Compile(NewRuntimeConfig().WithCodeProfile(s), identityI32Module())
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	if !bytes.Equal(plain.code, c.code) {
		t.Fatal("profiling changed generated bytes")
	}
	a, err := Instantiate(c)
	if err != nil {
		t.Fatal(err)
	}
	defer a.Close()
	b, err := Instantiate(c)
	if err != nil {
		t.Fatal(err)
	}
	defer b.Close()
	events, status := s.Read(0)
	if status.Dropped != 0 || len(events) != 1 {
		t.Fatal(events, status)
	}
	im := events[0].Image
	if err := jitprofile.ValidateRegions(im.Regions, im.Size); err != nil {
		t.Fatal(err)
	}
	if runtime.GOARCH == "amd64" {
		if len(im.Unwind) == 0 || im.UnwindCoverage != "amd64-fixed-frames-and-adapters" {
			t.Fatalf("missing compiler unwind rules: %+v", im)
		}
	} else if len(im.Unwind) != 0 || im.UnwindCoverage != "unsupported" {
		t.Fatalf("unqualified target claims unwind support: %+v", im)
	}
	if len(im.Functions) != 1 || im.Functions[0].Index != 0 {
		t.Fatal(im.Functions)
	}
	c.Close()
	a.Close()
	events, _ = s.Read(0)
	if len(events) != 1 {
		t.Fatal("early retirement", events)
	}
	got, err := b.Invoke("identity", 41)
	if err != nil || got[0] != 41 {
		t.Fatal(got, err)
	}
	b.Close()
	events, _ = s.Read(0)
	if len(events) != 2 || events[1].Kind != "retire" {
		t.Fatal(events)
	}
	if !bytes.Equal(events[0].Image.Code, plain.code) {
		t.Fatal("bytes not retained after teardown")
	}
}
func TestCodeProfileStartAndImportIndex(t *testing.T) {
	s := NewCodeProfile(CodeProfileOptions{IncludeCode: true})
	defer s.Close()
	c, err := Compile(NewRuntimeConfig().WithCodeProfile(s), hostImportStartModule())
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	called := false
	imports := NewImports()
	imports.HostFunc("env", "f", func(HostCall) {
		called = true
		images, _, status := s.Snapshot()
		if status.Dropped != 0 || len(images) != 2 {
			t.Errorf("start executed before registrations: %d %+v", len(images), status)
		}
	})
	in, err := Instantiate(c, InstantiateOptions{Imports: imports})
	if err != nil {
		t.Fatal(err)
	}
	defer in.Close()
	if !called {
		t.Fatal("start not called")
	}
	events, _ := s.Read(0)
	if events[0].Image.Functions[0].Index != 1 {
		t.Fatal("local index mistaken for full index")
	}
	c.Close()
	in.Close()
	images, _, _ := s.Snapshot()
	if len(images) != 0 {
		t.Fatal("mapping retained", images)
	}
}
