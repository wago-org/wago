func TestCodeProfileAttachOwnedThunksAndConcurrentRetirement(t *testing.T) {
	rt := NewRuntime()
	defer rt.Close()
	mod, err := rt.Compile(benchReturningImportModule())
	if err != nil {
		t.Fatal(err)
	}
	defer mod.Close()
	owner, err := rt.NewHostFuncRef(slotHostFunc(func(_ HostModule, args, results []uint64) { results[0] = args[0] + 1 }), FuncSig{Params: []ValType{ValI32}, Results: []ValType{ValI32}})
	if err != nil {
		t.Fatal(err)
	}
	defer owner.Close()
	instantiate := func() (*Instance, error) {
		return rt.Instantiate(context.Background(), mod, WithImports(testImports("env.f", owner)))
	}
	held, err := instantiate()
	if err != nil {
		t.Fatal(err)
	}
	defer held.Close()
	if len(held.thunkMem) == 0 {
		t.Fatal("missing private thunk")
	}
	s := NewCodeProfile(CodeProfileOptions{IncludeCode: true})
	defer s.Close()
	start := make(chan struct{})
	errs := make(chan error, 8)
	var wg sync.WaitGroup
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-start
			for j := 0; j < 20; j++ {
				in, err := instantiate()
				if err != nil {
					errs <- err
					return
				}
				if _, err = in.Invoke("g", 41); err != nil {
					_ = in.Close()
					errs <- err
					return
				}
				if err = in.Close(); err != nil {
					errs <- err
					return
				}
			}
		}()
	}
	close(start)
	if err := mod.Compiled().AttachCodeProfile(s); err != nil {
		t.Fatal(err)
	}
	// Snapshot-plus-cursor and later events must not leave stale active mappings.
	initial, cursor, status := s.Snapshot()
	if status.Dropped != 0 || len(initial) < 2 {
		t.Fatal(len(initial), status)
	}
	active := map[uint64]bool{}
	for _, im := range initial {
		active[im.ID] = true
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Error(err)
	}
	if err := held.Close(); err != nil {
		t.Fatal(err)
	}
	if err := mod.Close(); err != nil {
		t.Fatal(err)
	}
	if err := rt.Close(); err != nil {
		t.Fatal(err)
	}
	events, status := s.Read(cursor)
	if status.Dropped != 0 {
		t.Fatal(status)
	}
	for _, event := range events {
		switch event.Kind {
		case "load":
			if active[event.ImageID] {
				t.Fatal("duplicate generation", event.ImageID)
			}
			active[event.ImageID] = true
		case "retire":
			if !active[event.ImageID] {
				t.Fatal("retirement without observation", event.ImageID)
			}
			delete(active, event.ImageID)
		}
	}
	if len(active) != 0 {
		t.Fatal("unretired mappings", active)
	}
	images, _, _ := s.Snapshot()
	if len(images) != 0 {
		t.Fatal("active images after teardown", images)
	}
	all, _ := s.Read(0)
	foundPrivate := false
	for _, event := range all {
		if event.Kind == "load" {
			im := event.Image
			if len(im.Code) != int(im.Size) {
				t.Fatal("missing stable bytes", im.ID)
			}
			if im.Preexisting && len(im.Regions) == 1 && im.Regions[0].Kind == "host-thunk" {
				foundPrivate = true
			}
		}
	}
	if !foundPrivate {
		t.Fatal("lost preexisting private thunk")
	}
	cc := held.c.loadCodeCache()
	cc.profileMu.Lock()
	retained := len(cc.liveProfileThunks)
	cc.profileMu.Unlock()
	if retained != 0 {
		t.Fatal("retained retired thunk views", retained)
	}
}
