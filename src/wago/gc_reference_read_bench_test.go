package wago

import "testing"

func gcStructReferenceReadLoopModule() []byte {
	typ := []byte{0x5f, 0x01, 0x6d, 0x01} // final struct with mutable nullable eqref
	global := []byte{0x64, 0x00, 0x00, 0xd0, 0x6d, 0xfb, 0x00, 0x00, 0x0b}
	body := []byte{
		0x01, 0x02, 0x7f, // index, sum
		0x02, 0x40, 0x03, 0x40,
		0x20, 0x01, 0x20, 0x00, 0x4f, 0x0d, 0x01,
		0x20, 0x02, 0x23, 0x00, 0xfb, 0x02, 0x00, 0x00, 0xd1, 0x6a, 0x21, 0x02,
		0x20, 0x01, 0x41, 0x01, 0x6a, 0x21, 0x01, 0x0c, 0x00,
		0x0b, 0x0b, 0x20, 0x02, 0x0b,
	}
	return gcInstructionBenchmarkModuleWithTypes([][]byte{typ}, body, global)
}

func BenchmarkGCStructReferenceRead(b *testing.B) {
	benchmarkGCInstructionLoop(b, gcStructReferenceReadLoopModule(), 1)
}
