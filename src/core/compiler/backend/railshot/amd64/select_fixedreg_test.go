//go:build linux && amd64

package amd64

import (
	"testing"

	"github.com/wago-org/wago/src/core/compiler/wasm"
)

func TestSelectFlagsPreservesBranchesAcrossFixedRegisterCondition(t *testing.T) {
	// The nested selects materialize the outer false branch before its condition.
	// That condition contains an integer division, which reclaims RAX/RDX. The
	// branch value must therefore live outside the fixed-role registers until the
	// final CMOV. Floyd-Warshall's initializer exposed this as every row after its
	// first element being stored as zero.
	body := []byte{
		0x01, 0x07, 0x7f, // seven i32 locals
		0x41, 0x00, 0x21, 0x04, // local 4 = 0
		0x03, 0x40, // outer loop (one iteration)
		0x41, 0x00, 0x21, 0x05, // local 5 = 0
		0x41, 0x01, 0x21, 0x06, // local 6 = 1
		0x20, 0x01, 0x21, 0x00, // local 0 = local 1
		0x41, 0x00, 0x21, 0x02, // local 2 = 0
		0x03, 0x40, // inner loop
		0x20, 0x02, 0x20, 0x04, 0x6a, // address = local 2 + local 4
		0x41, 0xe7, 0x07, // outer select true value = 999
		0x41, 0xe7, 0x07, // middle select true value = 999
		0x41, 0xe7, 0x07, // inner select true value = 999
		0x20, 0x06, 0x20, 0x05, 0x41, 0x00, 0x6c, 0x6b,
		0x20, 0x03, 0x20, 0x00, 0x41, 0x07, 0x6e, 0x41, 0x1c, 0x6c, 0x6a,
		0x20, 0x02, 0x46, 0x1b, // inner select
		0x41, 0x01, 0x1b, // middle select
		0x20, 0x00, 0x41, 0x0b, 0x6e, 0x20, 0x02, 0x46, 0x1b, // outer select; condition divides
		0x36, 0x02, 0x00, // store
		0x20, 0x01, 0x20, 0x05, 0x6a, 0x21, 0x05,
		0x20, 0x01, 0x20, 0x06, 0x6a, 0x21, 0x06,
		0x20, 0x00, 0x41, 0x01, 0x6a, 0x21, 0x00,
		0x20, 0x02, 0x41, 0x04, 0x6a, 0x22, 0x02,
		0x41, 0x08, 0x47, 0x0d, 0x00, // repeat twice
		0x0b, 0x0b,
		0x41, 0x04, 0x28, 0x02, 0x00, // load memory[4]
		0x0b,
	}
	m := modMem(t, 2, nil, []wasm.ValType{wasm.I32}, body)
	got, _, err := runMemAmd64(t, m, nil)
	if err != nil {
		t.Fatal(err)
	}
	if got != 999 {
		t.Fatalf("select branch was clobbered by fixed-register condition: got %d, want 999", got)
	}
}
