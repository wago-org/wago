// Command geninstrnames packs instruction names into strings and offset tables.
// Separate ranges let feature-trimmed builds omit names for disabled opcodes.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

func main() {
	in := flag.String("in", "types.go", "InstrKind source file")
	out := flag.String("out", "instr_names_gen.go", "generated Go output")
	flag.Parse()

	src, err := os.ReadFile(*in)
	if err != nil {
		fatal(err)
	}
	start := bytes.Index(src, []byte("InstrInvalid InstrKind = iota"))
	if start < 0 {
		fatal(fmt.Errorf("InstrKind enum start not found in %s", *in))
	}
	endRel := bytes.Index(src[start:], []byte("numInstrKinds"))
	if endRel < 0 {
		fatal(fmt.Errorf("InstrKind enum sentinel not found in %s", *in))
	}

	var names []string
	for _, line := range strings.Split(string(src[start:start+endRel]), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 || !strings.HasPrefix(fields[0], "Instr") {
			continue
		}
		name := strings.TrimPrefix(fields[0], "Instr")
		if name == "" {
			fatal(fmt.Errorf("empty instruction name in line %q", line))
		}
		names = append(names, name)
	}
	if len(names) == 0 {
		fatal(fmt.Errorf("no instruction names found in %s", *in))
	}

	groups := instructionNameGroups(names)
	var generated strings.Builder
	generated.WriteString("// This Source Code Form is subject to the terms of the Mozilla Public\n// License, v. 2.0. If a copy of the MPL was not distributed with this\n// file, You can obtain one at https://mozilla.org/MPL/2.0/.\n//\n// SPDX-License-Identifier: MPL-2.0\n// Copyright (c) 2026 Wago authors and contributors\n\n")
	generated.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	generated.WriteString("package wasm\n\n")
	generated.WriteString("import \"github.com/wago-org/wago/internal/buildfeatures\"\n\n")
	fmt.Fprintf(&generated, "const instrKindNameCount = %d\n\n", len(names))

	for i, group := range groups {
		fmt.Fprintf(&generated, "const instrNameBlob%d = \"\" +\n", i)
		for j, name := range group.names {
			suffix := " +"
			if j == len(group.names)-1 {
				suffix = ""
			}
			fmt.Fprintf(&generated, "\t%s%s\n", strconv.Quote(name), suffix)
		}
		writeOffsets(&generated, fmt.Sprintf("instrNameOffsets%d", i), group.names)
	}

	generated.WriteString("const instrKindNameBlob = ")
	for i := range groups {
		if i != 0 {
			generated.WriteString(" +\n")
		}
		fmt.Fprintf(&generated, "instrNameBlob%d", i)
	}
	generated.WriteByte('\n')
	writeOffsets(&generated, "instrKindNameOffsets", names)
	generated.WriteString("var _ [numInstrKinds-instrKindNameCount]struct{}\n")
	generated.WriteString("var _ [instrKindNameCount-numInstrKinds]struct{}\n\n")

	generated.WriteString("func profileInstructionName(kind InstrKind) string {\nswitch {\n")
	for i, group := range groups {
		fmt.Fprintf(&generated, "case kind <= Instr%s:\n", group.names[len(group.names)-1])
		if group.condition != "" {
			fmt.Fprintf(&generated, "if %s {\n", group.condition)
		}
		fmt.Fprintf(&generated, "index := kind - Instr%s\n", group.names[0])
		fmt.Fprintf(&generated, "return instrNameBlob%d[instrNameOffsets%d[index]:instrNameOffsets%d[index+1]]\n", i, i, i)
		if group.condition != "" {
			generated.WriteString("}\n")
		}
	}
	generated.WriteString("}\nreturn \"Invalid\"\n}\n")

	formatted, err := format.Source([]byte(generated.String()))
	if err != nil {
		fatal(fmt.Errorf("format generated source: %w", err))
	}
	old, _ := os.ReadFile(*out)
	if bytes.Equal(old, formatted) {
		return
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fatal(err)
	}
}

type nameGroup struct {
	names     []string
	condition string
}

// The enum retains stable numeric IDs across builds. Group names in enum
// order without moving opcodes or repeating the spelling of every opcode.
func instructionNameGroups(names []string) []nameGroup {
	ranges := []struct {
		first, last, condition string
	}{
		{"Throw", "ThrowRef", "buildfeatures.ExceptionHandling != 0"},
		{"ReturnCall", "ReturnCallIndirect", "buildfeatures.TailCall != 0"},
		{"CallRef", "CallRef", "buildfeatures.TypedFunctionReferences != 0"},
		{"ReturnCallRef", "ReturnCallRef", "buildfeatures.TypedFunctionReferences != 0 && buildfeatures.TailCall != 0"},
		{"TryTable", "TryTable", "buildfeatures.ExceptionHandling != 0"},
		{"TableGet", "TableSet", "buildfeatures.ReferenceTypes != 0"},
		{"MemoryAtomicNotify", "AtomicCmpxchg", "buildfeatures.Threads != 0"},
		{"I32Extend8S", "I64Extend32S", "buildfeatures.SignExtensionOps != 0"},
		{"RefNull", "RefFunc", "buildfeatures.ReferenceTypes != 0"},
		{"RefEq", "RefEq", "buildfeatures.GC != 0"},
		{"RefAsNonNull", "RefAsNonNull", "buildfeatures.TypedFunctionReferences != 0"},
		{"StringConst", "StringConst", "buildfeatures.GC != 0"},
		{"BrOnNull", "BrOnNonNull", "buildfeatures.TypedFunctionReferences != 0"},
		{"StringNewUtf8Array", "I31GetU", "buildfeatures.GC != 0"},
		{"I32TruncSatF32S", "I64TruncSatF64U", "buildfeatures.NonTrappingFloatToIntConversion != 0"},
		{"MemoryInit", "MemoryFill", "buildfeatures.BulkMemoryOperations != 0"},
		{"TableInit", "TableCopy", "buildfeatures.BulkMemoryOperations != 0 && buildfeatures.ReferenceTypes != 0"},
		{"TableGrow", "TableFill", "buildfeatures.ReferenceTypes != 0"},
		{"V128Load", "F64x2ConvertLowI32x4U", "buildfeatures.SIMD != 0"},
		{"I8x16RelaxedSwizzle", "I32x4RelaxedDotI8x16I7x16AddS", "buildfeatures.RelaxedSIMD != 0"},
		{"I64Add128", "I64MulWideU", "buildfeatures.WideArithmetic != 0"},
	}
	indexes := make(map[string]int, len(names))
	for i, name := range names {
		indexes[name] = i
	}
	var groups []nameGroup
	next := 0
	for _, span := range ranges {
		start, haveStart := indexes[span.first]
		finish, haveFinish := indexes[span.last]
		if !haveStart || !haveFinish || start < next || finish < start {
			fatal(fmt.Errorf("invalid feature range from %s to %s", span.first, span.last))
		}
		if start != next {
			groups = append(groups, nameGroup{names: names[next:start]})
		}
		groups = append(groups, nameGroup{names: names[start : finish+1], condition: span.condition})
		next = finish + 1
	}
	if next != len(names) {
		groups = append(groups, nameGroup{names: names[next:]})
	}
	return groups
}

func writeOffsets(out *strings.Builder, variable string, names []string) {
	fmt.Fprintf(out, "\nvar %s = [...]uint16{\n", variable)
	offset := 0
	for i := 0; i <= len(names); i++ {
		if i%12 == 0 {
			out.WriteByte('\t')
		}
		fmt.Fprintf(out, "%d,", offset)
		if i%12 == 11 || i == len(names) {
			out.WriteByte('\n')
		} else {
			out.WriteByte(' ')
		}
		if i < len(names) {
			offset += len(names[i])
			if offset > int(^uint16(0)) {
				fatal(fmt.Errorf("instruction name blob is %d bytes; uint16 offsets overflow", offset))
			}
		}
	}
	out.WriteString("}\n\n")
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "geninstrnames:", err)
	os.Exit(1)
}
