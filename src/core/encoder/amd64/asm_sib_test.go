func TestBaseDisplacementBoundaries(t *testing.T) {
	cases := []struct {
		name string
		base Reg
		disp int32
		want []byte
	}{
		{"rax -129", RAX, -129, []byte{0x44, 0x8b, 0x80, 0x7f, 0xff, 0xff, 0xff}},
		{"rax -128", RAX, -128, []byte{0x44, 0x8b, 0x40, 0x80}},
		{"rax -1", RAX, -1, []byte{0x44, 0x8b, 0x40, 0xff}},
		{"rax 0", RAX, 0, []byte{0x44, 0x8b, 0x00}},
		{"rax 1", RAX, 1, []byte{0x44, 0x8b, 0x40, 0x01}},
		{"rax 127", RAX, 127, []byte{0x44, 0x8b, 0x40, 0x7f}},
		{"rax 128", RAX, 128, []byte{0x44, 0x8b, 0x80, 0x80, 0x00, 0x00, 0x00}},
		{"rsp -129", RSP, -129, []byte{0x44, 0x8b, 0x84, 0x24, 0x7f, 0xff, 0xff, 0xff}},
		{"rsp -128", RSP, -128, []byte{0x44, 0x8b, 0x44, 0x24, 0x80}},
		{"rsp -1", RSP, -1, []byte{0x44, 0x8b, 0x44, 0x24, 0xff}},
		{"rsp 0", RSP, 0, []byte{0x44, 0x8b, 0x04, 0x24}},
		{"rsp 1", RSP, 1, []byte{0x44, 0x8b, 0x44, 0x24, 0x01}},
		{"rsp 127", RSP, 127, []byte{0x44, 0x8b, 0x44, 0x24, 0x7f}},
		{"rsp 128", RSP, 128, []byte{0x44, 0x8b, 0x84, 0x24, 0x80, 0x00, 0x00, 0x00}},
		{"rbp -129", RBP, -129, []byte{0x44, 0x8b, 0x85, 0x7f, 0xff, 0xff, 0xff}},
		{"rbp -128", RBP, -128, []byte{0x44, 0x8b, 0x45, 0x80}},
		{"rbp -1", RBP, -1, []byte{0x44, 0x8b, 0x45, 0xff}},
		{"rbp 0", RBP, 0, []byte{0x44, 0x8b, 0x45, 0x00}},
		{"rbp 1", RBP, 1, []byte{0x44, 0x8b, 0x45, 0x01}},
		{"rbp 127", RBP, 127, []byte{0x44, 0x8b, 0x45, 0x7f}},
		{"rbp 128", RBP, 128, []byte{0x44, 0x8b, 0x85, 0x80, 0x00, 0x00, 0x00}},
		{"r12 0", R12, 0, []byte{0x45, 0x8b, 0x04, 0x24}},
		{"r12 127", R12, 127, []byte{0x45, 0x8b, 0x44, 0x24, 0x7f}},
		{"r12 128", R12, 128, []byte{0x45, 0x8b, 0x84, 0x24, 0x80, 0x00, 0x00, 0x00}},
		{"r13 0", R13, 0, []byte{0x45, 0x8b, 0x45, 0x00}},
		{"r13 127", R13, 127, []byte{0x45, 0x8b, 0x45, 0x7f}},
		{"r13 128", R13, 128, []byte{0x45, 0x8b, 0x85, 0x80, 0x00, 0x00, 0x00}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var a Asm
			a.Load32(R8, tc.base, tc.disp)
			if !bytes.Equal(a.B, tc.want) {
				t.Fatalf("Load32 bytes = % x, want % x", a.B, tc.want)
			}
		})
	}
}

func TestSIBDisplacementBoundaries(t *testing.T) {
	cases := []struct {
		disp int32
		want []byte
	}{
		{-129, []byte{0x43, 0x89, 0xbc, 0x08, 0x7f, 0xff, 0xff, 0xff}},
		{-128, []byte{0x43, 0x89, 0x7c, 0x08, 0x80}},
		{-1, []byte{0x43, 0x89, 0x7c, 0x08, 0xff}},
		{0, []byte{0x43, 0x89, 0x3c, 0x08}},
		{1, []byte{0x43, 0x89, 0x7c, 0x08, 0x01}},
		{127, []byte{0x43, 0x89, 0x7c, 0x08, 0x7f}},
		{128, []byte{0x43, 0x89, 0xbc, 0x08, 0x80, 0x00, 0x00, 0x00}},
	}
	for _, tc := range cases {
		t.Run(strconv.FormatInt(int64(tc.disp), 10), func(t *testing.T) {
			var a Asm
			a.StoreIdx(R8, R9, RDI, tc.disp, 4)
			if !bytes.Equal(a.B, tc.want) {
				t.Fatalf("StoreIdx(%d) bytes = % x, want % x", tc.disp, a.B, tc.want)
			}
		})
	}
}

func TestCompactDisplacementsAcrossMemoryEncoders(t *testing.T) {
	cases := []struct {
		name string
		emit func(*Asm)
		want []byte
	}{
		{"byte indexed", func(a *Asm) { a.StoreIdx(R8, R9, RSP, -128, 1) }, []byte{0x43, 0x88, 0x64, 0x08, 0x80}},
		{"word indexed", func(a *Asm) { a.StoreIdx(R13, RSI, RDI, 127, 2) }, []byte{0x66, 0x41, 0x89, 0x7c, 0x35, 0x7f}},
		{"dword immediate rsp", func(a *Asm) { a.StoreImm32Mem(RSP, 0, 1) }, []byte{0xc7, 0x04, 0x24, 0x01, 0x00, 0x00, 0x00}},
		{"qword rbp zero", func(a *Asm) { a.Load64(R8, RBP, 0) }, []byte{0x4c, 0x8b, 0x45, 0x00}},
		{"imul r13 zero", func(a *Asm) { a.ImulRM(R9, R13, 0, true) }, []byte{0x4d, 0x0f, 0xaf, 0x4d, 0x00}},
		{"rsp lea disp8", func(a *Asm) { a.LeaRsp(R8, -128) }, []byte{0x4c, 0x8d, 0x44, 0x24, 0x80}},
		{"scaled lea zero", func(a *Asm) { a.LeaScaled(R8, R9, R10, 1, 0) }, []byte{0x4f, 0x8d, 0x04, 0x51}},
		{"scaled lea rbp zero", func(a *Asm) { a.LeaScaled(RAX, RBP, RCX, 0, 0) }, []byte{0x48, 0x8d, 0x44, 0x0d, 0x00}},
		{"sse r12 disp8", func(a *Asm) { a.FLoadDisp(R8, R12, 127, false) }, []byte{0xf3, 0x45, 0x0f, 0x10, 0x44, 0x24, 0x7f}},
		{"vex r12 disp8", func(a *Asm) { a.VMovdquLoadDisp(R9, R12, 32) }, []byte{0xc4, 0x41, 0x7a, 0x6f, 0x4c, 0x24, 0x20}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var a Asm
			tc.emit(&a)
			if !bytes.Equal(a.B, tc.want) {
				t.Fatalf("encoding = % x, want % x", a.B, tc.want)
			}
		})
	}
}

func TestSIBZeroDisplacementPreservesRBPAndR13Base(t *testing.T) {
	for _, tc := range []struct {
		name string
		base Reg
		want []byte
	}{
		{name: "rbp", base: RBP, want: []byte{0x89, 0x7c, 0x35, 0x00}},
		{name: "r13", base: R13, want: []byte{0x41, 0x89, 0x7c, 0x35, 0x00}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var a Asm
			a.StoreIdx(tc.base, RSI, RDI, 0, 4)
			if !bytes.Equal(a.B, tc.want) {
				t.Fatalf("StoreIdx bytes = % x, want % x", a.B, tc.want)
			}
		})
	}
}
