// signExtensionModule inventories the five scalar sign-extension proposal
// instructions. Each row repeatedly perturbs a runtime value before narrowing
// and sign-extending it, keeping the measured instruction in a dependent chain.
func signExtensionModule(arg int) isaModule {
	type extensionCase struct {
		name, typ, op, seed string
	}
	cases := []extensionCase{
		{"i32_extend8_s", "i32", "i32.extend8_s", "(local.get $n)"},
		{"i32_extend16_s", "i32", "i32.extend16_s", "(local.get $n)"},
		{"i64_extend8_s", "i64", "i64.extend8_s", "(i64.extend_i32_s (local.get $n))"},
		{"i64_extend16_s", "i64", "i64.extend16_s", "(i64.extend_i32_s (local.get $n))"},
		{"i64_extend32_s", "i64", "i64.extend32_s", "(i64.extend_i32_s (local.get $n))"},
	}
	var b strings.Builder
	b.WriteString(";; GENERATED by corpus/gen — do not edit by hand.\n(module\n")
	exports := make([]string, 0, len(cases))
	for _, tc := range cases {
		fmt.Fprintf(&b, "  (func (export %q) (param $n i32) (result %s)\n    (local $acc %s)\n", tc.name, tc.typ, tc.typ)
		fmt.Fprintf(&b, "    (local.set $acc %s)\n", tc.seed)
		b.WriteString("    (block $done (loop $loop\n      (br_if $done (i32.eqz (local.get $n)))\n")
		perturb := "(local.get $n)"
		if tc.typ == "i64" {
			perturb = "(i64.extend_i32_u (local.get $n))"
		}
		fmt.Fprintf(&b, "      (local.set $acc (%s.xor (local.get $acc) %s))\n", tc.typ, perturb)
		for i := 0; i < isaUnroll; i++ {
			fmt.Fprintf(&b, "      (local.set $acc (%s (local.get $acc)))\n", tc.op)
		}
		b.WriteString("      (local.set $n (i32.sub (local.get $n) (i32.const 1)))\n      (br $loop)))\n    (local.get $acc))\n")
		exports = append(exports, tc.name)
	}
	b.WriteString(")\n")
	return isaModule{file: "isa_signext.wasm", wat: b.String(), exports: exports, arg: arg}
}
